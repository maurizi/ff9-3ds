#!/usr/bin/env python3
"""The effect modules' links on the DS (Makefile, ds_FXOVL).

  fx_extern.py NM OUT.ld OBJ...   EXTERN() of every symbol the modules' objects use and none of them defines, so the
                                  main executable keeps it for the modules' links (--just-symbols) after its
                                  --gc-sections. A module using another module's symbol is an error: one module is
                                  loaded at a time.
  fx_extern.py --build-id OUT.s   a new random build id (psx_fx_build_id) for the main executable; the module pack
                                  carries it so the game refuses a pack linked against another build.
"""
import os
import re
import subprocess
import sys


def module_of(path):
    m = re.search(r"/(fx_[0-9a-f]{3}(?:_\d+)?)(?:/|\.o$|_[0-9A-F]+\.o$)", path) or re.search(r"img_(fx_[^/.]+)\.o$", path)
    if not m:
        sys.exit(f"fx_extern.py: can't tell the module of {path}")
    return m.group(1)


def main():
    if sys.argv[1] == "--build-id":
        value = int.from_bytes(os.urandom(4), "little")
        with open(sys.argv[2], "w") as f:
            f.write('    .section .rodata.psx_fx_build_id,"a"\n    .balign 4\n    .global psx_fx_build_id\n'
                    f"psx_fx_build_id:\n    .4byte 0x{value:08X}\n")
        return
    nm, out, objs = sys.argv[1], sys.argv[2], sys.argv[3:]
    defined, used = {}, {}
    for obj in objs:
        mod = module_of(obj)
        for line in subprocess.run([nm, obj], check=True, capture_output=True, text=True).stdout.splitlines():
            parts = line.split()
            if len(parts) == 2 and parts[0] == "U":
                used.setdefault(parts[1], set()).add(mod)
            elif len(parts) == 3 and parts[1] in "TDBRCVW":  # global definitions, weak ones too
                defined.setdefault(parts[2], set()).add(mod)
    bad = []
    names = []
    for sym, mods in sorted(used.items()):
        owners = defined.get(sym)
        if owners is None:
            names.append(sym)
        elif mods - owners:
            bad.append(f"{sym}: defined in {sorted(owners)}, used by {sorted(mods - owners)}")
    if bad:
        sys.exit("fx_extern.py: effect modules use each other's symbols:\n  " + "\n  ".join(bad))
    layout = dict(re.findall(r"#define (OVL0B_\w+)\s+(0x[0-9A-Fa-f]+)", open("port/include/ovl0b_layout.h").read()))
    at, area, end = (int(layout[k], 16) for k in ("OVL0B_AT", "OVL0B_FX_AREA_AT", "OVL0B_FX_AREA_END"))
    with open(out, "w") as f:
        f.write("/* Generated by tools/fx_extern.py: what the effect modules use from the main executable, and where the\n"
                " * loaded one goes (port/include/ovl0b_layout.h: ovl_0b's dead MIPS code range). */\n")
        f.write(f"psx_fx_area = psx_ram + 0x{at + area:X};\npsx_fx_area_size = 0x{end - area:X};\n")
        for sym in names:
            f.write(f"EXTERN({sym})\n")


main()
