#!/usr/bin/env python3
"""Field event-script argument layouts for the port's script walker (port/game/field_map.c): build/gen/evt_ops.h from
the decomp's tools/evtscript/optab.json (widths taken from evt_execInstr's C) with the corrections its disassembler
(tools/evtscript/evtdis.py) applies. Code-derived, no game data.   gen_evt_ops.py OPTAB.json OUT.h"""
import json, sys

t = json.load(open(sys.argv[1]))
page1, page2 = {}, {}
for k, v in t.items():
    op = int(k, 16)
    if op >= 0xFF00:
        page2[op & 0xFF] = v['args']
    elif op != 0xFF:
        page1[op] = v['args']
# evtdis.py's corrections: evt_modelOpField's field-only ops, and cases whose C reads differ from the generated widths
page1.update({0x7F: '', 0x80: '', 0x81: 'bb', 0x82: 'ww', 0x83: 'b', 0x84: '', 0x85: 'b', 0xD8: 'bb'})
page1.update({0x29: 'N', 0xFE: 'bbbbb', 0x4B: 'bbb', 0xDE: 'bw', 0x4F: 'r', 0x1C: 'b', 0x22: 'b', 0x32: 'bb'})

def table(name, d):
    rows = []
    for op in range(256):
        rows.append('NULL' if op not in d else '"%s"' % d[op])
    return 'static const char *const %s[256] = {\n%s\n};\n' % (
        name, '\n'.join('    ' + ', '.join(rows[i:i + 8]) + ',' for i in range(0, 256, 8)))

with open(sys.argv[2], 'w') as f:
    f.write('/* generated by tools/gen_evt_ops.py from the decomp\'s tools/evtscript/optab.json: each op\'s arguments after\n'
            ' * its flags byte (b 1, w 2, t 3 bytes, r a raw byte, N a count then that many s16 pairs); NULL unknown */\n')
    f.write(table('evt_op_args', page1))
    f.write(table('evt_op2_args', page2))
