#!/usr/bin/env python3
"""Turn the first link pass's undefined symbols into stubs, and report them.

Usage: gen_stubs.py SCAN_LOG OUT.c

Every undefined function becomes a stub that stops with its name (port_stub_hit), so the image links and the
first call to something missing says exactly what. Undefined data (a name the decomp's symbol files don't place)
gets a small zeroed placeholder. The list is written next to OUT as stubs.txt: it is the port's to-do list
(port/psx for PsyQ, decomp src_equiv/ for asm routines, docs/decomp-requests.md).
"""
import re
import sys
from pathlib import Path

log, out = Path(sys.argv[1]), Path(sys.argv[2])
text = log.read_text()
names = sorted(set(re.findall(r"undefined reference to `([^']+)'", text)))

# The port's own code naming something undefined is a mistake, not a to-do: usually a decomp rename the port didn't
# follow (after a decomp update the old name links to a stub that stops the game at its first call). Fail the build.
own = sorted(set(re.findall(r"/port/[^:\n]+\.c:\d+:[^\n]*undefined reference to `([^']+)'", text)))
own = [n for n in own if not re.match(r"^(?:o[0-9a-f]{2}_)?(?:D_|g_|s_|jtbl_)", n)
       and not n.startswith("ctr_")]  # (ctr_*: the 3DS renderer's, absent on the host where nothing reaches them)
if own:
    for m in re.finditer(r"(/port/[^:\n]+\.c:\d+):[^\n]*undefined reference to `([^']+)'", text):
        if m.group(2) in own:
            print(f"gen_stubs: {m.group(1)}: port code calls undefined {m.group(2)} (renamed in the decomp?)", file=sys.stderr)
    sys.exit(1)
DATA = re.compile(r"^(?:o[0-9a-f]{2}_)?(?:D_|g_|s_|jtbl_)")

lines = ["/* Generated by tools/gen_stubs.py: things the port doesn't provide yet. */",
         '#include "psx_runtime.h"', ""]
listing = []
for n in names:
    if DATA.match(n):
        lines.append(f"unsigned char {n}[16] __attribute__((aligned(8)));")
        listing.append(f"data {n}")
    else:
        lines.append(f'void {n}(void) {{ port_stub_hit("{n}"); }}')
        listing.append(f"func {n}")
out.write_text("\n".join(lines) + "\n")
(out.parent / "stubs.txt").write_text("\n".join(listing) + "\n")
print(f"gen_stubs: {sum(1 for l in listing if l.startswith('func'))} functions, "
      f"{sum(1 for l in listing if l.startswith('data'))} data symbols stubbed ({out.parent / 'stubs.txt'})")
